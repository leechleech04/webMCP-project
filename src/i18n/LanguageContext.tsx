const interpolate = (value: string, vars?: Record<string, string | number>) =>
  value.replace(/\{(\w+)\}/g, (_, key: string) => String(vars?.[key] ?? `{${key}}`));

interface LanguageValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  componentName: (id: string, fallback: string) => string;
  categoryName: (id: string, fallback: string) => string;
  caseName: (value: string) => string;
}

const defaultValue: LanguageValue = {
  language: "en",
  setLanguage: () => undefined,
  t: (key, vars) => interpolate(en[key] ?? key, vars),
  componentName: (_id, fallback) => fallback,
  categoryName: (_id, fallback) => fallback,
  caseName: (value) => value,
};

const LanguageContext = createContext<LanguageValue>(defaultValue);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    if (typeof window === "undefined") return "en";
    try {
      return window.localStorage.getItem(STORAGE_KEY) === "ko" ? "ko" : "en";
    } catch {
      return "en";
    }
  });

  useEffect(() => {
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Language selection still works for the current session.
    }
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<LanguageValue>(() => ({
    language,
    setLanguage,
    t: (key, vars) => interpolate((language === "ko" ? ko : en)[key] ?? key, vars),
    componentName: (id, fallback) => language === "ko" ? componentNamesKo[id] ?? fallback : fallback,
    categoryName: (id, fallback) => language === "ko" ? categoryNamesKo[id] ?? fallback : fallback,
    caseName: (name) => language === "ko" ? caseNamesKo[name] ?? name : name,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export const useLanguage = () => useContext(LanguageContext);
